export function scoreSentiment(text) {
  const words = String(text || "").toLowerCase().split(/[^a-z]+/).filter(Boolean);
  let score = 0;
  for (const w of words) score += SENTIMENT_LEXICON[w] || 0;
  return score;
}

export function rankReviews(reviews) {
  return [...(reviews || [])].sort((a, b) => {
    const sa = (a.rating || 0) * 2 + scoreSentiment(a.comment);
    const sb = (b.rating || 0) * 2 + scoreSentiment(b.comment);
    return sb - sa;
  });
}

