export const ORDER_TRANSITIONS = {
  DRAFT: ['PENDING_PAYMENT', 'CANCELLED'],
  PENDING_PAYMENT: ['PAID', 'CANCELLED'],
  PAID: ['PROCESSING', 'REFUNDED'],
  PROCESSING: ['PICKING', 'CANCELLED'],
  PICKING: ['PACKED', 'CANCELLED'],
  PACKED: ['SHIPPED'],
  SHIPPED: ['IN_TRANSIT'],
  IN_TRANSIT: ['OUT_FOR_DELIVERY', 'DELIVERED'],
  OUT_FOR_DELIVERY: ['DELIVERED'],
  DELIVERED: ['COMPLETED', 'RETURN_REQUESTED'],
  COMPLETED: ['RETURN_REQUESTED'],
  RETURN_REQUESTED: ['RETURNED', 'COMPLETED'],
  RETURNED: ['REFUNDED'],
  CANCELLED: [],
  REFUNDED: [],
};

export function canTransition(from, to) {
  const allowed = ORDER_TRANSITIONS[from] || [];
  return allowed.includes(to);
}

export function transitionOrder(order, toState, meta = {}) {
  if (!order || !order.status) throw new Error("Invalid order");
  if (!canTransition(order.status, toState)) {
    return { ok: false, error: `Cannot transition ${order.status} -> ${toState}` };
  }
  const history = [...(order.statusHistory || []), { from: order.status, to: toState, at: Date.now(), ...meta }];
  return { ok: true, order: { ...order, status: toState, statusHistory: history, updatedAt: Date.now() } };
}

