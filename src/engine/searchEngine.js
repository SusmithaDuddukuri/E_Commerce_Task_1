/** Full-text search index builder for product catalog */

const STOP_WORDS = new Set(["the","a","an","and","or","for","of","to","in","on","with","by","is","at"]);

export function tokenize(text) {
  return String(text || "")
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .split(/\s+/)
    .filter((t) => t.length > 1 && !STOP_WORDS.has(t));
}

export function buildIndex(products) {
  const inverted = new Map();
  const docs = new Map();
  for (const p of products || []) {
    const blob = [p.name, p.tagline, p.description, p.category, p.badge, ...(p.colors || [])].join(" ");
    const tokens = tokenize(blob);
    docs.set(p.id, { product: p, tokens });
    const tf = new Map();
    for (const t of tokens) tf.set(t, (tf.get(t) || 0) + 1);
    for (const [term, count] of tf) {
      if (!inverted.has(term)) inverted.set(term, []);
      inverted.get(term).push({ id: p.id, tf: count / tokens.length });
    }
  }
  return { inverted, docs, size: docs.size };
}

export function searchIndex(index, query, limit = 20) {
  if (!index || !query) return [];
  const terms = tokenize(query);
  if (!terms.length) return [];
  const scores = new Map();
  for (const term of terms) {
    const postings = index.inverted.get(term) || [];
    const idf = Math.log(1 + index.size / (1 + postings.length));
    for (const { id, tf } of postings) {
      scores.set(id, (scores.get(id) || 0) + tf * idf);
    }
  }
  return [...scores.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, limit)
    .map(([id, score]) => ({ id, score, product: index.docs.get(id)?.product }));
}

