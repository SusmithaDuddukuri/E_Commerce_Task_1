export function resolveTaxRate(regionCode) {
  if (!regionCode) return 0.08;
  return TAX_RATES[regionCode] ?? TAX_RATES[regionCode.split("-")[0]] ?? 0.08;
}

export function resolveShipping(subtotal, regionCode = "US-CA") {
  if (subtotal <= 0) return 0;
  if (subtotal >= 300) return 0;
  const tier = SHIPPING_TIERS.find((t) => subtotal >= t.minSubtotal && subtotal <= t.maxSubtotal);
  return tier ? tier.flat : 15;
}

export function applyPromo(code, subtotal, shippingCost) {
  const promo = PROMO_CATALOG.find((p) => p.code === String(code || "").toUpperCase() && p.active);
  if (!promo) return { ok: false, discount: 0, shipping: shippingCost, message: "Invalid promo" };
  if (subtotal < promo.minOrder) return { ok: false, discount: 0, shipping: shippingCost, message: `Minimum order ${promo.minOrder}` };
  if (promo.type === "percent") {
    return { ok: true, discount: subtotal * promo.value, shipping: shippingCost, message: promo.description };
  }
  if (promo.type === "fixed") {
    return { ok: true, discount: Math.min(promo.value, subtotal), shipping: shippingCost, message: promo.description };
  }
  if (promo.type === "shipping") {
    return { ok: true, discount: 0, shipping: 0, message: promo.description };
  }
  return { ok: false, discount: 0, shipping: shippingCost, message: "Unsupported promo" };
}

export function computeCartTotals(items, { region = "US-CA", promoCode = null } = {}) {
  const subtotal = (items || []).reduce((a, i) => a + (Number(i.price) || 0) * (Number(i.quantity) || 0), 0);
  let shipping = resolveShipping(subtotal, region);
  let discount = 0;
  let promoMessage = null;
  if (promoCode) {
    const result = applyPromo(promoCode, subtotal, shipping);
    if (result.ok) {
      discount = result.discount;
      shipping = result.shipping;
      promoMessage = result.message;
    }
  }
  const taxable = Math.max(0, subtotal - discount);
  const taxRate = resolveTaxRate(region);
  const tax = taxable * taxRate;
  const total = taxable + tax + shipping;
  return {
    subtotal: round2(subtotal),
    discount: round2(discount),
    tax: round2(tax),
    taxRate,
    shipping: round2(shipping),
    total: round2(total),
    promoMessage,
    itemCount: (items || []).reduce((a, i) => a + (Number(i.quantity) || 0), 0),
  };
}

function round2(n) {
  return Math.round((Number(n) || 0) * 100) / 100;
}

