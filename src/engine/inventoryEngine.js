export function createLedgerFromSeed(seed = SKU_SEED_TABLE) {
  const initial = {};
  for (const row of seed) initial[row.sku] = row.onHand;
  return new InventoryLedger(initial);
}

/** Determine whether an inventory row is at or below its reorder point. */
export function needsReorder(row) {
  if (!row) return false;
  return (row.onHand ?? 0) <= (row.reorderPoint ?? 0);
}

export function listReorderCandidates(seed = SKU_SEED_TABLE) {
  return seed.filter(needsReorder);
}
