/** Inventory & stock reservation engine for Aura Commerce */

export class InventoryLedger {
  constructor(initial = {}) {
    this.stock = { ...initial };
    this.reservations = new Map();
    this.history = [];
  }

  getAvailable(sku) {
    const onHand = this.stock[sku] ?? 0;
    let reserved = 0;
    for (const r of this.reservations.values()) {
      if (r.sku === sku) reserved += r.qty;
    }
    return Math.max(0, onHand - reserved);
  }

  setStock(sku, qty) {
    this.stock[sku] = Math.max(0, Number(qty) || 0);
    this.history.push({ type: "SET", sku, qty: this.stock[sku], at: Date.now() });
  }

  adjust(sku, delta) {
    this.stock[sku] = Math.max(0, (this.stock[sku] ?? 0) + delta);
    this.history.push({ type: "ADJUST", sku, delta, at: Date.now() });
    return this.stock[sku];
  }

  reserve(orderId, sku, qty) {
    const available = this.getAvailable(sku);
    if (qty > available) return { ok: false, reason: "INSUFFICIENT_STOCK", available };
    const key = `${orderId}:${sku}`;
    this.reservations.set(key, { orderId, sku, qty, at: Date.now() });
    this.history.push({ type: "RESERVE", orderId, sku, qty, at: Date.now() });
    return { ok: true, available: available - qty };
  }

  release(orderId, sku) {
    const key = `${orderId}:${sku}`;
    const r = this.reservations.get(key);
    if (!r) return false;
    this.reservations.delete(key);
    this.history.push({ type: "RELEASE", orderId, sku, qty: r.qty, at: Date.now() });
    return true;
  }

  commit(orderId, sku) {
    const key = `${orderId}:${sku}`;
    const r = this.reservations.get(key);
    if (!r) return false;
    this.stock[sku] = Math.max(0, (this.stock[sku] ?? 0) - r.qty);
    this.reservations.delete(key);
    this.history.push({ type: "COMMIT", orderId, sku, qty: r.qty, at: Date.now() });
    return true;
  }

  snapshot() {
    return {
      stock: { ...this.stock },
      reservations: [...this.reservations.entries()].map(([k, v]) => ({ key: k, ...v })),
      historyLength: this.history.length,
    };
  }
}

