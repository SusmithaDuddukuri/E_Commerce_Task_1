export const CARD_BRANDS = [
  { brand: "visa", prefixes: ["4"] },
  { brand: "mastercard", prefixes: ["51","52","53","54","55"] },
  { brand: "amex", prefixes: ["34","37"] },
  { brand: "discover", prefixes: ["6011","65"] },
];

export function detectCardBrand(number) {
  const n = String(number || "").replace(/\s+/g, "");
  for (const b of CARD_BRANDS) {
    if (b.prefixes.some((p) => n.startsWith(p))) return b.brand;
  }
  return "unknown";
}

