export function weightedAverageCost(sku) {
  const layers = COST_LAYERS.filter((l) => l.sku === sku);
  if (!layers.length) return 0;
  let qty = 0, cost = 0;
  for (const l of layers) { qty += l.qty; cost += l.qty * l.unitCost; }
  return qty ? cost / qty : 0;
}

export function fifoCost(sku, qtyNeeded) {
  const layers = COST_LAYERS.filter((l) => l.sku === sku).sort((a, b) => a.receivedAt.localeCompare(b.receivedAt));
  let remaining = qtyNeeded;
  let total = 0;
  for (const l of layers) {
    if (remaining <= 0) break;
    const take = Math.min(remaining, l.qty);
    total += take * l.unitCost;
    remaining -= take;
  }
  return total;
}
