/** Build a fully formed product record for the storefront */
export function buildProductRecord(index, overrides = {}) {
  const categories = Object.keys(CATEGORY_TAXONOMY);
  const category = categories[index % categories.length];
  const sub = CATEGORY_TAXONOMY[category][index % CATEGORY_TAXONOMY[category].length];
  const price = 49 + ((index * 37) % 1400);
  const originalPrice = Math.round(price * (1.08 + (index % 7) * 0.03));
  const rating = Math.min(5, Math.round((3.6 + (index % 15) * 0.1) * 10) / 10);
  const stockCount = (index * 11) % 80;
  const img = PRODUCT_IMAGE_POOL[index % PRODUCT_IMAGE_POOL.length];
  const id = `aura-gen-${String(index).padStart(5, "0")}`;
  return {
    id,
    name: `Aura ${sub} ${Math.floor(index / 10) + 1} Mk.${(index % 9) + 1}`,
    tagline: `Precision ${sub.toLowerCase()} for daily luxury`,
    category,
    price,
    originalPrice,
    rating,
    reviewsCount: 3 + (index * 5) % 180,
    badge: index % 8 === 0 ? "Flagship" : index % 5 === 0 ? "New" : index % 3 === 0 ? "Best Seller" : null,
    inStock: stockCount > 0,
    stockCount,
    image: img,
    gallery: [img, PRODUCT_IMAGE_POOL[(index + 1) % PRODUCT_IMAGE_POOL.length]],
    description: `Hand-finished ${category.toLowerCase()} instrument. Serial ${index} uses adaptive materials, quiet mechanics, and continuous firmware support.`,
    colors: ["Obsidian", "Silver", "Champagne", "Midnight"].slice(0, 2 + (index % 3)),
    specs: {
      material: ["Aerospace Aluminum", "Zirconia", "Carbon Fiber", "Ceramic"][index % 4],
      warranty: `${12 + (index % 24)} Months`,
      origin: ["Japan", "Germany", "Switzerland", "USA", "Italy"][index % 5],
      weight: `${70 + (index % 450)}g`,
    },
    reviews: [{
      id: `rv-${index}-1`,
      author: ["Alex Lee", "Jordan Park", "Sam Singh", "Taylor Rossi", "Morgan Nguyen"][index % 5],
      rating: Math.min(5, Math.max(3, Math.round(rating))),
      date: `2026-08-${String((index % 28) + 1).padStart(2, "0")}`,
      comment: "Excellent build quality and thoughtful packaging. Exceeds expectations.",
    }],
    ...overrides,
  };
}

