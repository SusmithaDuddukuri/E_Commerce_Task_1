export function getProductById(id) {
  return INITIAL_PRODUCTS.find(p => p.id === id) || null;
}

export function searchProducts(query, products = INITIAL_PRODUCTS) {
  const q = (query || '').toLowerCase().trim();
  if (!q) return products;
  return products.filter(p =>
    p.name.toLowerCase().includes(q) ||
    (p.description || '').toLowerCase().includes(q) ||
    (p.tagline || '').toLowerCase().includes(q) ||
    (p.category || '').toLowerCase().includes(q) ||
    (p.badge || '').toLowerCase().includes(q)
  );
}

export function filterProducts(products, { category, inStockOnly, minPrice, maxPrice, minRating } = {}) {
  return products.filter(p => {
    if (category && category !== 'All' && p.category !== category) return false;
    if (inStockOnly && !p.inStock) return false;
    if (minPrice != null && p.price < minPrice) return false;
    if (maxPrice != null && p.price > maxPrice) return false;
    if (minRating != null && p.rating < minRating) return false;
    return true;
  });
}

export function sortProducts(products, sortBy) {
  const list = [...products];
  switch (sortBy) {
    case 'price-asc': return list.sort((a, b) => a.price - b.price);
    case 'price-desc': return list.sort((a, b) => b.price - a.price);
    case 'rating': return list.sort((a, b) => b.rating - a.rating);
    case 'newest': return list.sort((a, b) => b.id.localeCompare(a.id));
    case 'discount': return list.sort((a, b) => {
      const da = a.originalPrice ? (a.originalPrice - a.price) / a.originalPrice : 0;
      const db = b.originalPrice ? (b.originalPrice - b.price) / b.originalPrice : 0;
      return db - da;
    });
    default: return list;
  }
}
